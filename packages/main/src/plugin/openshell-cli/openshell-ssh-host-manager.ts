import { inject, injectable } from 'inversify';

import { CliToolRegistry } from '/@/plugin/cli-tool-registry.js';
import { ConfigurationRegistry } from '/@/plugin/configuration-registry.js';
import { Exec } from '/@/plugin/util/exec.js';
import type { CliToolInfo } from '/@api/cli-tool-info.js';

import { OpenshellSshConfig } from './openshell-ssh-config.js';
import { OpenshellWorkspaceDefaults } from './openshell-workspace-defaults.js';

const SANDBOX_NAME_PATTERN = /^[A-Za-z0-9][A-Za-z0-9._-]*$/;
const OPEN_SHELL_TOOL_NAME = 'openshell';
const OPEN_SHELL_CONFIGURATION_SECTION = 'openshell';
const OPEN_SHELL_BINARY_PATH_KEY = 'binary.path';
const PROXY_SUBCOMMAND = ' ssh-proxy ';
const SHELL_SAFE_PATTERN = /^[A-Za-z0-9_@%+=:,./-]+$/;
const ESCAPED_SINGLE_QUOTE = "'\\''";

interface HostBlock {
  alias: string;
  block: string;
}

/**
 * Installs OpenShell sandboxes as local SSH hosts.
 *
 * The host block is generated by the embedded `openshell` CLI
 * (`openshell sandbox ssh-config`), so the `ProxyCommand` it contains points
 * at `openshell ssh-proxy` exactly like an upstream-managed setup. Kaiden only
 * merges the generated block into its managed SSH config.
 */
@injectable()
export class OpenshellSshHostManager {
  constructor(
    @inject(Exec)
    private readonly exec: Exec,
    @inject(CliToolRegistry)
    private readonly cliToolRegistry: CliToolRegistry,
    @inject(ConfigurationRegistry)
    private readonly configurationRegistry: ConfigurationRegistry,
    @inject(OpenshellSshConfig)
    private readonly sshConfig: OpenshellSshConfig,
  ) {}

  async install(sandboxName: string, gatewayName: string): Promise<void> {
    if (!SANDBOX_NAME_PATTERN.test(sandboxName)) {
      throw new Error(`invalid sandbox name "${sandboxName}"`);
    }
    const { alias, block } = await this.#renderHostBlock(sandboxName, gatewayName);
    await this.sshConfig.installHost(alias, block, gatewayName);
  }

  /**
   * Removes the SSH host blocks installed for a sandbox, matched on the
   * gateway and sandbox name their `ProxyCommand` targets. Returns the number
   * of removed blocks.
   */
  async remove(sandboxName: string, gatewayName: string): Promise<number> {
    return this.sshConfig.removeHost(sandboxName, gatewayName);
  }

  #openshellTool(): CliToolInfo | undefined {
    return this.cliToolRegistry.getCliToolInfos().find(tool => tool.name === OPEN_SHELL_TOOL_NAME);
  }

  async #renderHostBlock(sandboxName: string, gatewayName: string): Promise<HostBlock> {
    const tool = this.#openshellTool();
    const cliPath = tool?.path ?? OPEN_SHELL_TOOL_NAME;
    const args = [
      '--gateway',
      gatewayName,
      '--workspace',
      OpenshellWorkspaceDefaults.WORKSPACE,
      'sandbox',
      'ssh-config',
      sandboxName,
    ];
    let stdout: string;
    try {
      ({ stdout } = await this.exec.exec(cliPath, args));
    } catch (err: unknown) {
      const detail = err instanceof Error ? err.message : String(err);
      console.error(`openshell sandbox ssh-config failed: ${cliPath} ${args.join(' ')} — ${detail}`);
      throw new Error(
        `Failed to generate the SSH host config for workspace "${sandboxName}" on gateway "${gatewayName}": ${detail}`,
        { cause: err },
      );
    }
    const parsed = this.#parseHostBlock(stdout, sandboxName);
    return { ...parsed, block: this.#withProxyExecutable(parsed.block, this.#proxyExecutable(tool)) };
  }

  /**
   * The CLI renders its own absolute path in the `ProxyCommand`. Keep that for
   * embedded binaries and for a path configured in Kaiden, but fall back to a
   * bare `openshell` when the binary was only discovered on `PATH`, so the
   * block keeps following the user's PATH.
   */
  #proxyExecutable(tool: CliToolInfo | undefined): string {
    if (!tool?.path) {
      return OPEN_SHELL_TOOL_NAME;
    }
    if (tool.installationSource === 'extension') {
      return tool.path;
    }
    const configuredPath = this.configurationRegistry
      .getConfiguration(OPEN_SHELL_CONFIGURATION_SECTION)
      .get<string>(OPEN_SHELL_BINARY_PATH_KEY);
    return configuredPath && configuredPath === tool.path ? tool.path : OPEN_SHELL_TOOL_NAME;
  }

  #withProxyExecutable(block: string, executable: string): string {
    const lines = block.split('\n');
    const index = lines.findIndex(line => line.trimStart().startsWith('ProxyCommand '));
    const line = lines[index];
    if (line === undefined) {
      return block;
    }
    const commandEnd = line.indexOf('ProxyCommand') + 'ProxyCommand'.length;
    const rest = line.slice(commandEnd);
    const offset = rest.indexOf(PROXY_SUBCOMMAND);
    if (offset === -1) {
      console.warn(`[openshell-ssh-host] cannot replace the ProxyCommand executable in "${line.trim()}"`);
      return block;
    }
    lines[index] = `${line.slice(0, commandEnd)} ${this.#quoteExecutable(executable)}${rest.slice(offset)}`;
    return lines.join('\n');
  }

  #quoteExecutable(executable: string): string {
    if (SHELL_SAFE_PATTERN.test(executable)) {
      return executable;
    }
    return `'${executable.split("'").join(ESCAPED_SINGLE_QUOTE)}'`;
  }

  #parseHostBlock(stdout: string, sandboxName: string): HostBlock {
    const lines = stdout.split('\r\n').join('\n').trim().split('\n');
    const start = lines.findIndex(line => line.trimStart().startsWith('Host '));
    if (start === -1) {
      throw new Error(`The OpenShell CLI returned no SSH host block for workspace "${sandboxName}"`);
    }
    const blockLines = lines.slice(start);
    const alias = blockLines[0]?.trimStart().slice('Host '.length).split(/\s+/)[0];
    if (!alias) {
      throw new Error(`The OpenShell CLI returned a nameless SSH host block for workspace "${sandboxName}"`);
    }
    if (!blockLines.some(line => line.trimStart().startsWith('ProxyCommand '))) {
      throw new Error(
        `The OpenShell CLI returned an SSH host block without a ProxyCommand for workspace "${sandboxName}"`,
      );
    }
    return { alias, block: blockLines.join('\n') };
  }
}
